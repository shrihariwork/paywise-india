export type CardCategoryGroup =
  | 'FOOD_DINING_GROCERY'
  | 'UPI_TELECOM_FINTECH'
  | 'ECOMMERCE_CASHBACK'
  | 'PREMIUM_TRAVEL_ZERO_FOREX'
  | 'FUEL_ENTERTAINMENT_LIFESTYLE';

export type CardPaymentNetwork = 'VISA' | 'MASTERCARD' | 'RUPAY' | 'DINERS' | 'AMEX';

export interface CategoryAccelerator {
  categoryOrMerchant: string;
  mccs: string[];
  effectiveYieldBps: number; // 1000 = 10.0%, 750 = 7.5%, 500 = 5.0%
  monthlyCapInr: number | null;
  promoCode?: string;
  minTransactionInr?: number;
  requiresAppChannel?: string;
  isOnlineOnly?: boolean;
  isOfflineOnly?: boolean;
  description?: string;
}

export type DevaluationType =
  | 'DISCONTINUED'
  | 'LOUNGE_REMOVAL'
  | 'REWARD_REDUCTION'
  | 'CAP_REDUCTION'
  | 'EXCLUSION_ADDED';

export interface DevaluationWarning {
  date: string;
  type: DevaluationType;
  message: string;
  severity: 'HIGH' | 'MEDIUM' | 'LOW';
}

export interface CardProductRule {
  slug: string;
  name: string;
  issuer: string;
  network: CardPaymentNetwork;
  upiLinkable: boolean;
  annualFeeInr: number;
  waiverSpendInr: number | null;
  forexMarkupBps: number; // e.g. 0 for Scapia/ixigo/Mayura, 199 for SBI Elite, 350 for standard
  baseRewardRateBps: number; // e.g. 330 for 3.3%, 100 for 1.0%
  pointValueInr: number; // Rupee value per point
  categoryAccelerators: CategoryAccelerator[];
  devaluationWarnings: DevaluationWarning[];
  categoryGroup: CardCategoryGroup;
  cardColor: {
    gradient: string;
    textColor: string;
    badgeColor: string;
  };
  keyPerks: string[];
  exclusions?: string[];
  searchTags?: string[];
}

